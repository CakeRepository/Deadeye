test("move unlocks for dragging and the position persists across a reload", function()
	local W, AS, bar = Setup()
	local point, relativeTo, relativePoint, x, y = bar:GetPoint(1)
	H.Equal(point, "CENTER", "default anchor")
	H.Equal(y, -324, "default y: 30% of a 1080-unit screen below the center")
	H.False(bar.mouseEnabled, "mouse while locked")
	bar.scripts.OnDragStart(bar)
	H.False(bar.isMoving, "drag ignored while locked")
	W.Slash("move")
	H.False(W.env.DeadeyeDB.locked, "unlocked")
	H.True(bar:IsVisible(), "bar shown for dragging")
	H.True(bar.mouseEnabled, "mouse enabled")
	H.True(bar.mover:IsShown(), "blue drag overlay")
	bar.scripts.OnDragStart(bar)
	H.True(bar.isMoving, "dragging")
	-- Dropped with its bottom-left corner at (300, 400): its center is at (410, 408),
	-- which is (-550, -132) from the center of a 1920x1080 screen.
	W.dropPoint = { "BOTTOMLEFT", "BOTTOMLEFT", 300, 400 }
	bar.scripts.OnDragStop(bar)
	local pos = AS.db.position
	H.Equal(pos.x, -550, "saved x")
	H.Equal(pos.y, -132, "saved y")
	point, relativeTo, relativePoint, x, y = bar:GetPoint(1)
	H.Equal(point, "CENTER", "re-anchored by its center")
	H.Equal(x, -550, "anchor x")
	W.Slash("lock")
	H.True(W.env.DeadeyeDB.locked, "locked")
	H.False(bar:IsVisible(), "bar hidden after locking")

	local W2, AS2, bar2 = Setup({ savedVariables = W.env.DeadeyeDB })
	point, relativeTo, relativePoint, x, y = bar2:GetPoint(1)
	H.Equal(point, "CENTER", "restored point")
	H.Equal(relativeTo, W2.env.UIParent, "restored relative frame")
	H.Equal(relativePoint, "CENTER", "restored relative point")
	H.Equal(x, -550, "restored x")
	H.Equal(y, -132, "restored y")
end)

