test("the cast event for the same shot does not restart the cycle", function()
	local W, AS, bar, S = Setup()
	W.Fire("START_AUTOREPEAT_SPELL")
	local shotAt = W.now
	Shot(W)
	W.Fire("UNIT_SPELLCAST_SUCCEEDED", "player", "Cast-1", AUTO_SHOT)
