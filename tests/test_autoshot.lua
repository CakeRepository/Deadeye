test("the delay report adds up Auto Shot time lost to moving", function()
	local W, AS, bar, S = Setup()
	W.Slash("report on")
	W.inCombat = true
	W.Fire("PLAYER_REGEN_DISABLED")
	W.Fire("START_AUTOREPEAT_SPELL")
	Shot(W) -- 1: on time (first shot)
	W.Advance(2.0)
	Shot(W) -- 2: on time
	W.Advance(2.6)
	Shot(W) -- 3: 0.6s late (held back by moving)
	W.Advance(2.05)
	Shot(W) -- 4: 0.05s late, inside the tolerance
	W.Fire("STOP_AUTOREPEAT_SPELL")
	W.Advance(5)
	W.Fire("START_AUTOREPEAT_SPELL")
	Shot(W) -- 5: after a pause you chose, not counted as a delay
	H.Equal(S.fight.shots, 5, "shots this fight")
	H.Equal(S.fight.delayed, 1, "delayed shots")
	H.Near(S.fight.lost, 0.6, 1e-6, "seconds lost")
	W.Slash("stats")
	H.True(W.Printed("This fight: 5 shots, 1 held back, 0.6s of Auto Shot lost to moving or casting."), "stats mid-fight")
	W.inCombat = false
	W.Fire("PLAYER_REGEN_ENABLED")
	H.True(W.Printed("Last fight: 5 shots, 1 held back, 0.6s"), "report after the fight")
	H.Equal(S.fight.shots, 0, "counter reset for the next fight")
end)

