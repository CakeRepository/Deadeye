-- Scenario tests for the Auto Shot bar. Each test builds a fresh world, loads
-- the addon from the .toc and drives it with the events the Forever client sends.
local H, ROOT = ...

local RANGED, MAIN_HAND = 2, 0
local AUTO_SHOT = 75
-- Default world: 2.0s bow, 80ms world latency, so the aim window is 0.58s and
-- the reload phase of a 2.0s cycle ends at 1.42s.
local AIM = 0.58

local tests = {}
local function test(name, fn)
	tests[#tests + 1] = { name = name, fn = fn }
end

local function Setup(options)
	local W = H.NewWorld(options)
	H.LoadAddon(W, ROOT)
	local AS = W.ns.modules.AutoShot
	return W, AS, AS.bar, AS.state
end

local function Shot(W, speed)
	W.Fire("PLAYER_SWING", speed or 2.0, RANGED)
end

local function Label(bar)
	return bar.label.text
end

test("loads for a hunter and stays hidden until Auto Shot starts", function()
	local W, AS, bar = Setup()
	H.True(AS.enabled, "module enabled")
	H.True(AS.hasSwingEvent, "PLAYER_SWING registered")
	H.False(bar:IsVisible(), "bar visible")
	local saved = W.env.DeadeyeDB
	H.Equal(type(saved), "table", "saved variables")
	H.Equal(saved.modules.AutoShot.width, 220, "default width")
	H.Equal(#W.printed, 0, "chat lines printed at login")
end)

test("turning Auto Shot on shows only the aim window for the first shot", function()
	local W, AS, bar, S = Setup()
	W.Fire("START_AUTOREPEAT_SPELL")
	H.True(bar:IsVisible(), "bar visible")
	H.True(S.synthetic, "first-shot cycle")
	H.Equal(Label(bar), "Aim", "label")
	H.Near(bar.status.value, (2.0 - AIM) / 2.0, 0.001, "fill starts at the aim marker")
	H.Near(bar.aimZone.width, 220 * AIM / 2.0, 1e-6, "aim zone width")
end)

test("a shot starts a reload that turns into the aim window", function()
	local W, AS, bar, S = Setup()
	W.Fire("START_AUTOREPEAT_SPELL")
	Shot(W)
	H.False(S.synthetic, "real cycle")
	H.Equal(Label(bar), "Reload", "label after the shot")
	H.Equal(bar.time.text, "2.0", "time left")
	W.Advance(1.0)
	H.Equal(Label(bar), "Reload", "label mid reload")
	H.Near(bar.status.value, 0.5, 0.011, "fill mid reload")
	H.Equal(bar.time.text, "1.0", "time left mid reload")
	H.SameColor(bar.status.barColor, AS.db.colors.reload, "reload color")
	W.Advance(0.5) -- 1.5s: past 1.42
	H.Equal(Label(bar), "Aim", "label in the aim window")
	H.SameColor(bar.status.barColor, AS.db.colors.aim, "aim color")
	H.True(bar.spark:IsShown(), "spark shown mid cycle")
end)

test("moving in the aim window warns and the shot waits", function()
	local W, AS, bar, S = Setup()
	W.Fire("START_AUTOREPEAT_SPELL")
	Shot(W)
	W.Advance(1.5)
	W.moving = true
	W.Advance(0.04)
	H.Equal(Label(bar), "Moving", "label while moving in the aim window")
	H.SameColor(bar.status.barColor, AS.db.colors.blocked, "blocked color")
	W.Advance(0.6) -- cycle over, still moving
	H.Equal(Label(bar), "Moving", "label while the shot is held")
	H.Equal(bar.status.value, 1, "bar full while waiting")
	W.Fire("UNIT_SPELLCAST_FAILED_QUIET", "player", "Cast-AS", AUTO_SHOT)
	H.True(S.due, "shot marked due")
	W.Advance(0.04)
	H.Equal(bar.time.text, "0.5", "retry countdown")
	W.moving = false
	W.Advance(0.1)
	H.Equal(Label(bar), "Aim", "label once standing still")
	H.Equal(bar.time.text, "0.4", "retry countdown after stopping")
	Shot(W)
	H.Equal(Label(bar), "Reload", "next reload")
	H.False(S.due, "due cleared by the shot")
end)

