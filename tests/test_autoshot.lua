test("secret values in combat never reach math or comparisons", function()
	local W, AS, bar, S = Setup()
	W.inCombat = true
	W.statsSecret = true
	W.Fire("PLAYER_REGEN_DISABLED")
	W.Fire("UNIT_ATTACK_SPEED", "player")
	W.Fire("UNIT_RANGEDDAMAGE", "player")
	W.Fire("WEAPON_SLOT_CHANGED")
	H.Equal(S.speed, 2.0, "speed cached from before combat")
	W.Fire("START_AUTOREPEAT_SPELL")
	Shot(W, 2.2)
	H.Equal(S.speed, 2.2, "speed from PLAYER_SWING")
	W.Advance(0.5)
	W.Fire("PLAYER_SWING", H.Secret(2.3), RANGED)
	H.Equal(S.duration, 2.2, "secret duration falls back to the cached speed")
	W.Fire("PLAYER_SWING", 1.5, H.Secret(RANGED))
	H.Equal(S.duration, 2.2, "secret swing type ignored")
	W.Fire("UNIT_SPELLCAST_SUCCEEDED", "player", H.Secret("Cast-x"), H.Secret(AUTO_SHOT))
	W.Fire("UNIT_SPELLCAST_FAILED_QUIET", "player", H.Secret("Cast-x"), H.Secret(AUTO_SHOT))
	W.Fire("UNIT_SPELLCAST_START", "player", H.Secret("Cast-y"), H.Secret(19434))
	W.Advance(1.7) -- into the aim window of the 2.2s cycle
	H.Equal(Label(bar), "Casting", "secret cast still blocks the aim window")
	W.Fire("UNIT_SPELLCAST_FAILED", "player", H.Secret("Cast-y"), H.Secret(19434))
	W.Advance(0.04)
	H.Equal(Label(bar), "Aim", "secret cast cleared")
end)

